"""Inference on seo-agent-shaped traces, checked against its hand-written write and poll phases."""
import time

import pytest
from tenuo import Authorizer, SigningKey
from tenuo.exceptions import ConstraintViolation, ToolNotAuthorized

from warrantgen import Rule, infer, mint


def call(run, step, tool, **args):
    return {"run": run, "step": step, "tool": tool, "args": args}


BODY = "Lets AI search bots crawl the site and adds llms.txt.\n\nGenerated by fixagent."
TRACE = [
    call("r1", "write", "write_file", repo="acme/bakery", branch="fixagent/robots-1", path="public/robots.txt",
         size=812, text="User-agent: *\nAllow: /", message="fix robots"),
    call("r1", "write", "write_file", repo="acme/bakery", branch="fixagent/robots-1", path="public/llms.txt",
         size=2040, text="# Bakery\n", message="add llms.txt"),
    call("r1", "write", "open_pr", repo="acme/bakery", base="main", head="fixagent/robots-1", body=BODY),
    call("r1", "poll", "get_pr_state", repo="acme/bakery", number=7),
    call("r2", "write", "write_file", repo="acme/dentist", branch="fixagent/schema-2", path="app/layout.tsx",
         size=5100, text="export default function Layout() {}\n", message="add schema"),
    call("r2", "write", "open_pr", repo="acme/dentist", base="main", head="fixagent/schema-2", body=BODY),
    call("r2", "poll", "get_pr_state", repo="acme/dentist", number=12),
]


def test_write_phase_matches_hand_written_shape():
    steps, excluded = infer(TRACE)
    w = steps["write"]["write_file"]
    assert excluded == {}
    assert w["repo"].kind == "var" and w["repo"].value == "exact"  # phases.py: Exact(repo)
    assert w["path"] == Rule("var", "oneof", w["path"].note)       # phases.py: OneOf(paths)
    assert w["size"].kind == "range" and w["size"].value == (812, 5100)  # phases.py: Range(max=20000)
    assert w["text"].kind == "wildcard"                             # phases.py: Wildcard()
    assert w["branch"].kind == "var" and "fixagent/*" in w["branch"].note  # phases.py: Pattern("fixagent/*")
    assert steps["write"]["open_pr"]["base"] == Rule("exact", "main")
    assert steps["write"]["open_pr"]["body"].kind == "wildcard"
    assert steps["poll"]["get_pr_state"]["number"] == Rule("var", "exact", "differs per run")


def test_injected_run_is_excluded_not_learned():
    poisoned = TRACE + [call("r3", "explore", "read_file", repo="acme/bakery", path="../payments-api/.env")]
    steps, excluded = infer(poisoned)
    assert list(excluded) == ["r3"] and "explore" not in steps


def test_patterns_from_real_seo_agent_traces():
    # Several runs share a site, so a per-run value repeats across runs; timestamps share a long prefix.
    runs = [("a1", "acme/site", "fixagent/agent-20261018-014809", ["site-files"]),
            ("a2", "acme/site", "fixagent/agent-20261018-014833", ["org-schema", "site-files"]),
            ("b1", "bakery/web", "fixagent/agent-20261018-014851", ["org-schema"])]
    trace = [call(run, "s", "t", repo=repo, branch=branch, fixes=fixes) for run, repo, branch, fixes in runs]
    rules = infer(trace)[0]["s"]["t"]
    assert rules["repo"].kind == "var" and rules["repo"].value == "exact"
    assert "Pattern(fixagent/*)" in rules["branch"].note
    assert rules["fixes"] == Rule("subset", ["org-schema", "site-files"])


def test_taint_reason_is_short():
    convo = "x" * 5000 + ' {"path": "../payments-api/.env"} ' + "y" * 5000
    reasons = infer([call("r1", "s", "llm_turn", conversation=convo)])[1]["r1"]
    assert len(reasons[0]) < 100


def test_overrides():
    steps, _ = infer(TRACE, exact=["repo"])
    assert steps["write"]["write_file"]["repo"].kind == "oneof"
    steps, _ = infer([r for r in TRACE if r["run"] == "r1"], variables=["base"])
    assert steps["write"]["open_pr"]["base"].kind == "var"


def check(warrant, issuer, holder, tool, args):
    sig = bytes(warrant.sign(holder, tool, args, int(time.time())))
    Authorizer(trusted_roots=[issuer.public_key]).authorize_one(warrant, tool, args, signature=sig)


def test_minted_warrant_allows_observed_calls_and_denies_near_misses():
    steps, _ = infer(TRACE)
    issuer, holder = SigningKey.generate(), SigningKey.generate()
    w = mint(steps["write"], issuer, holder.public_key, ttl=300, bindings={
        "repo": "acme/bakery", "branch": "fixagent/robots-1", "head": "fixagent/robots-1",
        "path": ["public/robots.txt", "public/llms.txt"]})
    for r in TRACE[:3]:
        check(w, issuer, holder, r["tool"], r["args"])
    allowed = TRACE[0]["args"]
    for change in ({"repo": "acme/dentist"}, {"path": "public/.env"}, {"size": 5101}, {"branch": "main"}):
        with pytest.raises(ConstraintViolation, match=next(iter(change))):
            check(w, issuer, holder, "write_file", {**allowed, **change})
    with pytest.raises(ToolNotAuthorized):
        check(w, issuer, holder, "delete_repo", {"repo": "acme/bakery"})


def test_pinned_number_mints_as_one_point_range():
    steps, _ = infer(TRACE)
    issuer, holder = SigningKey.generate(), SigningKey.generate()
    w = mint(steps["poll"], issuer, holder.public_key, ttl=300, bindings={"repo": "acme/bakery", "number": 7})
    check(w, issuer, holder, "get_pr_state", {"repo": "acme/bakery", "number": 7})
    with pytest.raises(ConstraintViolation, match="number"):
        check(w, issuer, holder, "get_pr_state", {"repo": "acme/bakery", "number": 8})
